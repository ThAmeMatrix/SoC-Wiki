#!/usr/bin/env python3
"""Build the global "changed skill" term-jump map from the generated pages.

技能描述里的「技能变更为[烈风超重斩]」是方括号词条，richtext.render() 用
status_links 表解析，于是链到同名的「中括号介绍/烈风超重斩」状态页，
而不是变化后的技能页。scripts/socdecode/wiki.py 生成的「使用后技能变更」
区块里已经有正确的技能页链接（#/page/<pid>），这里把它们离线汇总成
window.WIKI_SKILL_SWITCHES，供 app.js 在点击词条时直接跳转；词条的 href
保持不变，鼠标悬停仍显示原来的状态说明（与抉择技能的处理一致）。

只依赖 data/pages/*.js，不需要游戏客户端，也不修改任何页面文件。
"""
from __future__ import annotations

import json
import re
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PAGES = ROOT / 'data' / 'pages'
OUT = ROOT / 'data' / 'skill-switch-links.js'

LINE = re.compile(r'<div class="skill-switch-line">(.*?)</div>', re.S)
# 「完整原文」里的 <h3>使用后技能变更</h3><div class="skill-switches"><div>…</div></div>
# 只取紧跟该标题的那个 div，避免吞掉后面「关联」等区块的链接。
BLOCK = re.compile(r'<h3>(?:使用后技能变更|由其它技能变更而来)</h3>'
                   r'\s*<div class="skill-switches">(.*?)</div></div>', re.S)
LINK = re.compile(r'<a href="#/page/(\d+)"[^>]*>(.*?)</a>', re.S)
TAG = re.compile(r'<[^>]+>')
# 与 app.js 点击兜底用的归一化规则保持一致。
NORMALIZE = re.compile(r'[\[\]【】\s]')
DOTS = str.maketrans('·•‧・', '----')


def key_of(text: str) -> str:
    return NORMALIZE.sub('', re.sub(TAG, '', text)).translate(DOTS).strip()


def load_page(path: Path):
    text = path.read_text('utf8')
    start, end = text.find('{'), text.rfind('}')
    if start < 0 or end <= start:
        return None
    try:
        return json.loads(text[start:end + 1])
    except ValueError:
        return None


def collect():
    votes: dict[str, Counter] = defaultdict(Counter)
    blocks = 0
    for path in sorted(PAGES.glob('*.js')):
        doc = load_page(path)
        if not doc:
            continue
        desc = (doc.get('fields') or {}).get('技能描述') or ''
        html = doc.get('html') or ''
        chunks = LINE.findall(desc) + BLOCK.findall(html)
        if not chunks:
            continue
        blocks += 1
        for chunk in chunks:
            for match in LINK.finditer(chunk):
                name = key_of(match.group(2))
                if name:
                    votes[name][int(match.group(1))] += 1
    return votes, blocks


def resolve(votes: dict[str, Counter]):
    """同名技能可能既有客户端技能页又有旧档案页；优先客户端页（1e8+），
    其次得票多者，最后取较大 id，保证输出稳定。"""
    out = {}
    for name, counter in sorted(votes.items()):
        target = sorted(counter.items(),
                        key=lambda kv: (kv[0] >= 100_000_000, kv[1], kv[0]),
                        reverse=True)[0][0]
        out[name] = target
    return out


def main():
    votes, blocks = collect()
    mapping = resolve(votes)
    conflicts = sum(1 for c in votes.values() if len(c) > 1)
    body = json.dumps(mapping, ensure_ascii=False, separators=(',', ':'), sort_keys=True)
    OUT.write_text(
        '/* Generated by scripts/build_skill_switch_links.py from data/pages/*.js.\n'
        '   变化技能名 -> 技能词条页 id；app.js 用它把描述里的 [XXX] 词条点击直接跳到技能页。 */\n'
        f'window.WIKI_SKILL_SWITCHES={body};\n', 'utf8')
    print(f'变化技能词条映射：{len(mapping)} 个名字，来自 {blocks} 个技能页，'
          f'{conflicts} 个同名冲突已消解 → {OUT.relative_to(ROOT)}')


if __name__ == '__main__':
    main()
